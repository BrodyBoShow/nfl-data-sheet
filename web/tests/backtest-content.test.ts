// Build-time backtest content (docs/phases/P6.md step 4). Runs the parser on the real
// committed report and coefficients. If scripts/backtest.py is re-run and the numbers
// change, the exact-value assertions below are meant to fail and be updated
// deliberately.
import { readFileSync } from "node:fs";

import { Marked } from "marked";
import { describe, expect, it } from "vitest";

import {
  buildSummary,
  edgeIntervals,
  renderReport,
  reportProvenance,
  winRateBuckets,
} from "../scripts/backtest-content.mjs";
import { statusLine, type BacktestSummary } from "../lib/backtest";
import { formatBound, formatFixed, formatInterval, formatSeasonRange } from "../lib/format";

const report = readFileSync(new URL("../../docs/backtest_report.md", import.meta.url), "utf8");
const coefficients = JSON.parse(
  readFileSync(new URL("../../pipeline/synthesis/model_coefficients.json", import.meta.url), "utf8"),
);
const summarize = (md = report, coef = coefficients): BacktestSummary => ({
  ...buildSummary(md, coef),
  sources: {},
});

describe("buildSummary on the committed report", () => {
  it("reads the out-of-sample margin MAE and the pooled spread edge correlation", () => {
    const s = summarize();
    expect(s.n_games).toBe(1615);
    expect(s.fit_seasons).toEqual([2019, 2020, 2021, 2022, 2023, 2024, 2025]);
    expect(s.test_seasons).toEqual([2020, 2021, 2022, 2023, 2024, 2025]);
    expect(s.margin_mae).toEqual({ model: 10.33, close: 9.76 });
    expect(s.spread_edge_corr).toEqual({ r: -0.033, ci: [-0.08, 0.015], n: 1615, validated: false });
    expect(s.validated_buckets).toEqual([]);
    expect(Object.keys(s.buckets).sort()).toEqual(["high", "low", "mid"]);
    expect(s.stability_floor).toBe(0.2262); // low bucket's stability_range[0]
  });

  it("produces the status line figures (step 4 done-when)", () => {
    const line = statusLine(summarize());
    expect(line.scope).toBe("Backtest 2020–25, 1,615 games out of sample");
    expect([line.marginModel, line.marginClose, line.edgeR, line.edgeCi]).toEqual([
      "10.33", "9.76", "−0.03", "[−0.08, 0.01]",
    ]);
    expect(line.edgeExact).toBe(
      "Correlation of (model spread − closing line) with (result − closing line): " +
        "r −0.033 [−0.080, 0.015], n 1,615",
    );
    expect(line.validation).toBe("not validated");
  });
});

describe("the report for /method", () => {
  it("reads its provenance and win-rate tables", () => {
    const s = summarize();
    expect(s.report).toEqual({ script: "scripts/backtest.py", generated_utc: "2026-09-30 22:48" });
    expect(s.win_rates).toHaveLength(10);
    expect(Math.max(...s.win_rates.map((b) => b.rate))).toBe(0.526);
    expect(s.win_rates.find((b) => b.rate === 0.526)).toMatchObject({ market: "spread", bucket: "2–3", decided: 287, wins: 151 });
  });

  it("renders every table in the report as a table, headings demoted two levels", () => {
    const html = renderReport(report, Marked);
    expect(html.match(/<table class="data report-table">/g)).toHaveLength(19);
    expect(html).toContain("<th>|edge| pts</th>");
    expect(html).toContain("<th>Per-game |Δ projection|</th>");
    expect(html.startsWith("<h3>P5 backtest report</h3>")).toBe(true);
  });

  it("throws on a table that doesn't parse, instead of rendering a paragraph of pipes", () => {
    const broken = report.replace("| Coefficient | Estimate | SE (clustered) |", "| Coefficient | Estimate |SE| |x|");
    expect(() => renderReport(broken, Marked)).toThrow(/table separators but/);
  });

  it("throws on a win rate that isn't Wins / Decided, or a missing Generated line", () => {
    expect(() => winRateBuckets(report.replace("| 2–3 | 293 | 287 | 151 | 6 | 0.526 |", "| 2–3 | 293 | 287 | 151 | 6 | 0.626 |"))).toThrow(/isn't Wins\/Decided/);
    expect(() => reportProvenance(report.replace("Generated by", "Made by"))).toThrow(/Generated by/);
  });
});

describe("buildSummary fails loudly instead of misreading", () => {
  const broken: [string, () => unknown, RegExp][] = [
    ["a renamed heading", () => summarize(report.replace("### Margin (home − away)", "### Margin")), /exactly one "### Margin/],
    ["a duplicated heading", () => summarize(report + "\n### Spread: correlation\n"), /found 2/],
    ["a renamed column", () => summarize(report.replace("| Close MAE | Close RMSE |", "| Closing MAE | Close RMSE |")), /no "Close MAE" column/],
    ["a missing All row", () => summarize(report.replace(/^\| \*\*All\*\* \| 1615 \| 10\.33 .*$/m, "")), /expected one "\*\*All\*\*" row/],
    ["a non-numeric cell", () => summarize(report.replace("| **All** | 1615 | 10.33 |", "| **All** | 1615 | n/a |")), /not a number/],
    ["a malformed CI", () => summarize(report.replace("| All | -0.033 | [-0.080, 0.015] |", "| All | -0.033 | -0.080 to 0.015 |")), /not an interval/],
    ["an unknown Validated value", () => summarize(report.replace("| [-0.080, 0.015] | 1615 | no |", "| [-0.080, 0.015] | 1615 | maybe |")), /Validated/],
    ["report and coefficients disagreeing on n", () => summarize(report, { ...coefficients, calibration: { ...coefficients.calibration, n_games: 1600 } }), /disagree: margin n 1615 vs calibration.n_games 1600/],
    ["report and coefficients disagreeing on seasons", () => summarize(report, { ...coefficients, calibration: { ...coefficients.calibration, test_seasons: [2021, 2022] } }), /disagree: report seasons/],
    ["coefficients without calibration", () => summarize(report, { model_version: "x" }), /no calibration block/],
    ["coefficients without fit_seasons", () => summarize(report, { ...coefficients, fit_seasons: undefined }), /no fit_seasons/],
    [
      "a bucket without a stability_range",
      () => summarize(report, { ...coefficients, calibration: { ...coefficients.calibration, buckets: { ...coefficients.calibration.buckets, low: { ...coefficients.calibration.buckets.low, stability_range: undefined } } } }),
      /no stability_range/,
    ],
  ];
  it.each(broken)("throws on %s", (_, run, message) => {
    expect(run).toThrow(message);
  });
});

describe("edgeIntervals", () => {
  it("reads all 20 intervals, buckets at the coefficients file's precision", () => {
    const iv = edgeIntervals(report, coefficients.calibration);
    expect(iv).toHaveLength(20);
    expect(iv.filter((e) => e.market === "spread").map((e) => e.slice)).toEqual([
      "All", "bucket low", "bucket mid", "bucket high", "2020", "2021", "2022", "2023", "2024", "2025",
    ]);
    const high = iv.find((e) => e.market === "spread" && e.slice === "bucket high")!;
    expect(high.ci_high).toBe(coefficients.calibration.buckets.high.edge_validation.spread.ci_high);
  });

  it("refuses a non-bucket bound the report prints as zero", () => {
    const md = report.replace("| 2025 | -0.121 | [-0.226, -0.018] |", "| 2025 | -0.121 | [-0.226, 0.000] |");
    expect(md).not.toBe(report);
    expect(() => edgeIntervals(md, coefficients.calibration)).toThrow(/prints as zero/);
  });
});

describe("the status line's validation wording follows the data", () => {
  it("names validated buckets rather than saying 'not validated'", () => {
    const s = { ...summarize(), validated_buckets: ["low spread"] };
    expect(statusLine(s).validation).toBe("validated: low spread");
  });
});

describe("format helpers", () => {
  it("uses a true minus and never shows a negative zero", () => {
    expect(formatFixed(-0.032, 2)).toBe("−0.03");
    expect(formatFixed(-0.004, 2)).toBe("0.00");
    expect(formatFixed(0.016, 2)).toBe("0.02");
  });
  it("keeps an interval bound's sign and a digit when it rounds to zero (P7 open item 22)", () => {
    expect(formatBound(-0.0004940895518897146, 3)).toBe("−0.0005"); // p5-v3 high-bucket spread
    expect(formatBound(0.00044696701709777246, 3)).toBe("0.0004"); // p5-v2's, once "0.000"
    expect(formatBound(0, 3)).toBe("0.000");
    expect(formatBound(-0.08, 3)).toBe("−0.080");
    expect(formatBound(1e-9, 3)).toBe("1.0e-9");
    expect(formatInterval([-0.16419621813533644, -0.0004940895518897146], 3)).toBe("[−0.164, −0.0005]");
    // A plain value still never shows a signed zero.
    expect(formatFixed(-0.0004, 3)).toBe("0.000");
  });
  it("collapses only contiguous season ranges", () => {
    expect(formatSeasonRange([2020, 2021, 2022])).toBe("2020–22");
    expect(formatSeasonRange([2020, 2022])).toBe("2020, 2022");
    expect(formatSeasonRange([2025])).toBe("2025");
  });
});
